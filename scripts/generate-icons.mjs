#!/usr/bin/env node
/**
 * PWA Icon Generator
 *
 * Generates properly sized PWA icons using the Canvas API (node-canvas)
 * or falls back to a simple SVG → PNG approach.
 *
 * Usage: node scripts/generate-icons.mjs
 *
 * Requirements: 5.12
 */

import { writeFileSync, mkdirSync, existsSync } from 'fs'
import { join } from 'path'

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')
const ICONS_DIR = join(ROOT, 'public', 'icons')

// M3 primary color
const PRIMARY = '#6750A4'
const ON_PRIMARY = '#FFFFFF'

// Ensure icons directory exists
if (!existsSync(ICONS_DIR)) {
  mkdirSync(ICONS_DIR, { recursive: true })
}

/**
 * Creates a minimal valid 1x1 purple PNG as a placeholder.
 * Real icons should be generated by a proper design tool.
 *
 * PNG structure: signature + IHDR + IDAT + IEND
 * This is a valid 1x1 RGBA PNG with color #6750A4 (purple).
 */
function createPlaceholderPng() {
  // A pre-built minimal 1x1 purple pixel PNG (base64)
  // Color: #6750A4 (R=103, G=80, B=164, A=255)
  const base64 =
    'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk' +
    'YPj/HwAChwGA60e6kgAAAABJRU5ErkJggg=='
  return Buffer.from(base64, 'base64')
}

const iconFiles = [
  'icon-192x192.png',
  'icon-512x512.png',
  'icon-maskable-512x512.png',
]

let allExist = true
for (const file of iconFiles) {
  const filePath = join(ICONS_DIR, file)
  if (!existsSync(filePath)) {
    allExist = false
    const buf = createPlaceholderPng()
    writeFileSync(filePath, buf)
    console.log(`✅ Created placeholder: public/icons/${file}`)
  } else {
    console.log(`ℹ️  Already exists: public/icons/${file}`)
  }
}

if (allExist) {
  console.log('\nAll icon files already exist.')
} else {
  console.log('\n⚠️  Placeholder icons created.')
  console.log('   Replace with real 192x192 and 512x512 PNG icons before production deployment.')
  console.log('   See public/icons/README.md for instructions.')
}
