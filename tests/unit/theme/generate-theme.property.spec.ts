// Feature: money-conversion-spa, Property 13: Theme Generation Produces Complete Palette
import { describe, it, expect } from 'vitest'
import fc from 'fast-check'
import {
  argbFromHex,
  hexFromArgb,
  TonalPalette,
  Hct,
} from '@material/material-color-utilities'

/**
 * Validates: Requirements 15.1
 *
 * Property 13: Theme Generation Produces Complete Palette
 * For any set of three valid 6-character hexadecimal seed colors (primary, secondary, tertiary),
 * the theme generator shall output CSS custom properties covering all 26 tonal stops
 * for each of the 6 color roles, and each output value shall be a valid hex color string.
 */

const TONAL_STOPS = [
  0, 4, 6, 10, 12, 17, 20, 22, 24, 25, 30, 35, 40, 50, 60, 70, 80, 87, 90,
  92, 94, 95, 96, 98, 99, 100,
]

const COLOR_ROLES = [
  'primary',
  'secondary',
  'tertiary',
  'neutral',
  'neutral-variant',
  'error',
] as const

const SEMANTIC_ROLES = [
  ['primary', 'primary', 40, 80],
  ['on-primary', 'primary', 100, 20],
  ['primary-container', 'primary', 90, 30],
  ['on-primary-container', 'primary', 10, 90],
  ['secondary', 'secondary', 40, 80],
  ['on-secondary', 'secondary', 100, 20],
  ['secondary-container', 'secondary', 90, 30],
  ['on-secondary-container', 'secondary', 10, 90],
  ['tertiary', 'tertiary', 40, 80],
  ['on-tertiary', 'tertiary', 100, 20],
  ['tertiary-container', 'tertiary', 90, 30],
  ['on-tertiary-container', 'tertiary', 10, 90],
  ['error', 'error', 40, 80],
  ['on-error', 'error', 100, 20],
  ['error-container', 'error', 90, 30],
  ['on-error-container', 'error', 10, 90],
  ['surface', 'neutral', 99, 10],
  ['on-surface', 'neutral', 10, 90],
  ['surface-variant', 'neutral-variant', 90, 30],
  ['on-surface-variant', 'neutral-variant', 30, 80],
  ['outline', 'neutral-variant', 50, 60],
  ['outline-variant', 'neutral-variant', 80, 30],
  ['inverse-surface', 'neutral', 20, 90],
  ['inverse-on-surface', 'neutral', 95, 20],
  ['inverse-primary', 'primary', 80, 40],
] as const

const HEX_COLOR_REGEX = /^#[0-9a-fA-F]{6}$/

/**
 * Replicates the core palette generation logic from scripts/generate-theme.mjs
 * to produce the same CSS output for arbitrary seed colors.
 */
function generateThemeCss(primary: string, secondary: string, tertiary: string): string {
  const palettes: Record<string, TonalPalette> = {
    primary: createTonalPalette(primary),
    secondary: createTonalPalette(secondary),
    tertiary: createTonalPalette(tertiary),
  }

  // Neutral derived from primary with low chroma
  const primaryArgb = argbFromHex(primary)
  const primaryHct = Hct.fromInt(primaryArgb)
  palettes['neutral'] = TonalPalette.fromHueAndChroma(primaryHct.hue, 4)
  palettes['neutral-variant'] = TonalPalette.fromHueAndChroma(primaryHct.hue, 8)

  // Error palette: fixed red hue
  palettes['error'] = TonalPalette.fromHueAndChroma(25, 84)

  // Build CSS output
  let css = '/* AUTO-GENERATED by scripts/generate-theme.mjs — DO NOT EDIT */\n\n'

  css += ':root {\n'
  css += '  /* Tonal palette stops */\n'
  for (const role of COLOR_ROLES) {
    for (const stop of TONAL_STOPS) {
      const hex = hexFromArgb(palettes[role].tone(stop))
      css += `  --md-ref-palette-${role}-${stop}: ${hex};\n`
    }
    css += '\n'
  }

  css += '  /* M3 semantic color roles — light */\n'
  for (const [name, source, lightTone] of SEMANTIC_ROLES) {
    const hex = hexFromArgb(palettes[source as string].tone(lightTone as number))
    css += `  --md-sys-color-${name}: ${hex};\n`
  }
  css += '}\n\n'

  css += '.dark {\n'
  css += '  /* M3 semantic color roles — dark */\n'
  for (const [name, source, , darkTone] of SEMANTIC_ROLES) {
    const hex = hexFromArgb(palettes[source as string].tone(darkTone as number))
    css += `  --md-sys-color-${name}: ${hex};\n`
  }
  css += '}\n'

  return css
}

function createTonalPalette(hexColor: string): TonalPalette {
  const argb = argbFromHex(hexColor)
  const hct = Hct.fromInt(argb)
  return TonalPalette.fromHueAndChroma(hct.hue, hct.chroma)
}

/**
 * Arbitrary generator for valid 6-character hex color strings.
 * Produces strings like "#a3f2c1".
 */
const hexColorArb = fc
  .array(fc.integer({ min: 0, max: 255 }), { minLength: 3, maxLength: 3 })
  .map(([r, g, b]) => {
    const hex = `#${r.toString(16).padStart(2, '0')}${g.toString(16).padStart(2, '0')}${b.toString(16).padStart(2, '0')}`
    return hex
  })

describe('Property 13: Theme Generation Produces Complete Palette', () => {
  it('generates CSS with all 26 tonal stops for each of 6 color roles, all valid hex values', { timeout: 30000 }, () => {
    fc.assert(
      fc.property(
        hexColorArb,
        hexColorArb,
        hexColorArb,
        (primary, secondary, tertiary) => {
          const css = generateThemeCss(primary, secondary, tertiary)

          // Verify :root and .dark selectors are present
          expect(css).toContain(':root {')
          expect(css).toContain('.dark {')

          // Verify all 6 color roles × 26 tonal stops = 156 tonal tokens
          for (const role of COLOR_ROLES) {
            for (const stop of TONAL_STOPS) {
              const tokenName = `--md-ref-palette-${role}-${stop}`
              expect(css).toContain(tokenName)

              // Extract the value for this token and verify it's a valid hex color
              const regex = new RegExp(`${tokenName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}:\\s*(#[0-9a-fA-F]{6})`)
              const match = css.match(regex)
              expect(match, `Token ${tokenName} should have a valid hex color value`).not.toBeNull()
              expect(match![1]).toMatch(HEX_COLOR_REGEX)
            }
          }

          // Verify total count: 6 roles × 26 stops = 156 tonal tokens
          const tonalTokenMatches = css.match(/--md-ref-palette-[a-z-]+-\d+/g)
          expect(tonalTokenMatches).not.toBeNull()
          expect(tonalTokenMatches!.length).toBe(156)

          // Verify semantic tokens are present in both :root and .dark
          for (const [name] of SEMANTIC_ROLES) {
            const semanticToken = `--md-sys-color-${name}`
            const semanticMatches = css.match(new RegExp(semanticToken.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g'))
            // Each semantic token appears twice: once in :root (light) and once in .dark
            expect(semanticMatches, `Semantic token ${semanticToken} should appear in both :root and .dark`).not.toBeNull()
            expect(semanticMatches!.length).toBeGreaterThanOrEqual(2)
          }

          // Verify all semantic token values are valid hex colors
          const allHexValues = css.match(/#[0-9a-fA-F]{6}/g)
          expect(allHexValues).not.toBeNull()
          for (const hex of allHexValues!) {
            expect(hex).toMatch(HEX_COLOR_REGEX)
          }
        },
      ),
    )
  })
})
